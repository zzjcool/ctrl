// `<sessionDir>/ctrl.json` — the machine binding (CONTRACT §8, PLAN §2.6).
//
// The event log belongs to pi-durable and ctrl adds no fields to it, so "which
// machine was this session working on, and where" lives next to it instead.
// Reading is best-effort by design: a corrupt sidecar must never make a session
// un-openable, it just means we fall back to the cwd recorded in the log.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { resolvePaths } from "../engine/durable.ts"

export interface SessionSidecar {
  machine: string
  remoteCwd: string
  createdAt: string
}

export const SIDECAR_FILENAME = "ctrl.json"

/** `<home>/sessions/<id>/ctrl.json` — pi-durable owns the directory, ctrl owns this file. */
export function sidecarPath(home: string | undefined, sessionId: string): string {
  if (!isSessionId(sessionId)) throw new Error(`invalid session id: ${sessionId}`)
  return path.join(resolvePaths(home).sessionDir(sessionId), SIDECAR_FILENAME)
}

export function writeSidecar(
  home: string | undefined,
  sessionId: string,
  value: SessionSidecar,
): SessionSidecar {
  const file = sidecarPath(home, sessionId)
  const record: SessionSidecar = {
    machine: value.machine,
    remoteCwd: value.remoteCwd,
    createdAt: value.createdAt,
  }
  mkdirSync(path.dirname(file), { recursive: true })
  writeFileSync(file, `${JSON.stringify(record, null, 2)}\n`, "utf8")
  return record
}

/** Undefined for a missing, unreadable, or malformed sidecar — never throws. */
export function readSidecar(home: string | undefined, sessionId: string): SessionSidecar | undefined {
  let file: string
  try {
    file = sidecarPath(home, sessionId)
  } catch {
    return undefined
  }
  let raw: string
  try {
    raw = readFileSync(file, "utf8")
  } catch {
    return undefined
  }
  try {
    const parsed: unknown = JSON.parse(raw)
    if (typeof parsed !== "object" || parsed === null) return undefined
    const candidate = parsed as Partial<SessionSidecar>
    if (typeof candidate.machine !== "string" || candidate.machine === "") return undefined
    if (typeof candidate.remoteCwd !== "string" || candidate.remoteCwd === "") return undefined
    return {
      machine: candidate.machine,
      remoteCwd: candidate.remoteCwd,
      createdAt: typeof candidate.createdAt === "string" ? candidate.createdAt : new Date(0).toISOString(),
    }
  } catch {
    return undefined
  }
}

/** Session ids are generated by pi-durable; this is the same charset it uses. */
export function isSessionId(value: string): boolean {
  return /^[a-zA-Z0-9_-]{1,80}$/.test(value)
}
